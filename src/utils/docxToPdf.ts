import { renderAsync } from 'docx-preview';
import mammoth from 'mammoth';
import html2canvas from 'html2canvas';
import { jsPDF } from 'jspdf';
import { DocxToPdfOptions } from '../types';

export interface DocxRenderResult {
  pageCount: number;
  previewElement: HTMLElement;
  htmlString?: string;
}

/**
 * Render DOCX into a target DOM container for real-time preview and export
 */
export async function renderDocxToContainer(
  fileOrBuffer: File | ArrayBuffer,
  container: HTMLElement
): Promise<void> {
  container.innerHTML = '';
  
  let buffer: ArrayBuffer;
  if (fileOrBuffer instanceof File) {
    buffer = await fileOrBuffer.arrayBuffer();
  } else {
    buffer = fileOrBuffer;
  }

  try {
    // Attempt high-fidelity docx-preview rendering
    await renderAsync(buffer, container, undefined, {
      className: 'docx',
      inWrapper: true,
      ignoreWidth: false,
      ignoreHeight: false,
      ignoreFonts: false,
      breakPages: true,
      ignoreLastRenderedPageBreak: false,
      experimental: true,
      trimXmlDeclaration: true,
      debug: false,
    });
  } catch (err) {
    console.warn('docx-preview failed, falling back to mammoth renderer', err);
    // Fallback: Mammoth
    const result = await mammoth.convertToHtml({ arrayBuffer: buffer });
    container.innerHTML = `
      <div class="docx-wrapper">
        <section class="docx p-8 md:p-12 max-w-[800px] mx-auto bg-white rounded-lg shadow-sm text-slate-800 leading-relaxed font-sans" dir="auto">
          ${result.value || '<p class="text-slate-400">محتوى المستند فارغ</p>'}
        </section>
      </div>
    `;
  }
}

/**
 * Convert rendered DOCX container to crisp PDF
 */
export async function convertDocxContainerToPdf(
  container: HTMLElement,
  options: DocxToPdfOptions,
  onProgress?: (progress: number, stepText: string) => void
): Promise<{ blob: Blob; url: string; size: number; pageCount: number }> {
  // Find all section elements generated by docx-preview
  let sections = container.querySelectorAll<HTMLElement>('.docx-wrapper > section.docx');
  if (!sections || sections.length === 0) {
    sections = container.querySelectorAll<HTMLElement>('section.docx');
  }

  const isLandscape = options.orientation === 'landscape';
  const orientation = isLandscape ? 'l' : 'p';
  const format = options.pageSize;

  // Standard dimensions in mm
  const pageWidthMm = format === 'letter' ? (isLandscape ? 279.4 : 215.9) : (isLandscape ? 297 : 210);
  const pageHeightMm = format === 'letter' ? (isLandscape ? 215.9 : 279.4) : (isLandscape ? 210 : 297);

  const pdf = new jsPDF({
    orientation,
    unit: 'mm',
    format: options.pageSize,
    compress: true,
  });

  const elementsToCapture: HTMLElement[] = [];

  if (sections.length > 0) {
    sections.forEach((sec) => elementsToCapture.push(sec));
  } else {
    // Fallback to whatever container child exists
    const firstChild = (container.firstElementChild as HTMLElement) || container;
    elementsToCapture.push(firstChild);
  }

  const total = elementsToCapture.length;

  for (let i = 0; i < total; i++) {
    const el = elementsToCapture[i];
    if (onProgress) {
      onProgress(
        Math.round((i / total) * 90),
        `جاري معالجة الصفحة ${i + 1} من ${total}...`
      );
    }

    // Capture using html2canvas with high scale for crisp text
    const canvas = await html2canvas(el, {
      scale: 2, // 2x DPI for sharp text and retina display
      useCORS: true,
      allowTaint: true,
      logging: false,
      backgroundColor: '#ffffff',
      windowWidth: 1200,
    });

    const imgData = canvas.toDataURL('image/jpeg', 0.95);

    if (i > 0) {
      pdf.addPage(format, orientation);
    }

    // Determine margins
    const marginMm = options.margins === 'none' ? 0 : options.margins === 'compact' ? 8 : 12;
    const printableW = pageWidthMm - marginMm * 2;
    const printableH = pageHeightMm - marginMm * 2;

    const imgAspect = canvas.width / canvas.height;
    const printAspect = printableW / printableH;

    let targetW = printableW;
    let targetH = printableH;

    if (imgAspect > printAspect) {
      targetW = printableW;
      targetH = printableW / imgAspect;
    } else {
      targetH = printableH;
      targetW = printableH * imgAspect;
    }

    const posX = marginMm + (printableW - targetW) / 2;
    const posY = marginMm;

    pdf.addImage(imgData, 'JPEG', posX, posY, targetW, targetH, undefined, 'FAST');

    if (options.addPageNumbers) {
      pdf.setFontSize(9);
      pdf.setTextColor(130, 130, 130);
      pdf.text(`${i + 1} / ${total}`, pageWidthMm / 2, pageHeightMm - 5, { align: 'center' });
    }
  }

  if (onProgress) {
    onProgress(95, 'جاري ضغط وتجهيز ملف PDF النهائي...');
  }

  const blob = pdf.output('blob');
  const url = URL.createObjectURL(blob);
  const size = blob.size;

  if (onProgress) {
    onProgress(100, 'اكتمل التحويل بنجاح!');
  }

  return {
    blob,
    url,
    size,
    pageCount: total,
  };
}
